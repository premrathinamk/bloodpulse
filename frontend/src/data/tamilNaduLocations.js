export const TAMIL_NADU_DISTRICTS = Object.keys(DISTRICT_TALUKS_MAP);

export function getTaluksForDistrict(district) {
  if (!district) return [];
  // Direct match or partial match
  if (DISTRICT_TALUKS_MAP[district]) {
    return DISTRICT_TALUKS_MAP[district];
  }
  const cleanDistrict = district.trim().toLowerCase();
  for (const [key, taluks] of Object.entries(DISTRICT_TALUKS_MAP)) {
    if (key.toLowerCase().includes(cleanDistrict) || cleanDistrict.includes(key.toLowerCase())) {
      return taluks;
    }
  }
  return [];
}
